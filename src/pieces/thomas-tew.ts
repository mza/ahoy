// The blade's curve in each pose, in cells: the guard, the bend's pull, the tip.
const BLADE: [number, number][][] = [
  [[43.75, 9.88], [44.0, 1.0], [75.0, 2.75]],
  [[42.52, 9.87], [42.15, 1.0], [73.25, 2.21]],
  [[41.29, 9.89], [40.3, 1.03], [71.47, 1.69]],
];

const LOOP = 6;
const RIPPLE = 2; // ripples a loop, travelling out from the hoist
const RUN = 1.1; // seconds a glint takes from the guard to the tip
const HALF = 0.12; // half its length, along the blade
const START = 1.5; // when it sets off

const smooth = (x: number) => (x <= 0 ? 0 : x >= 1 ? 1 : x * x * (3 - 2 * x));

export default function thomasTew(): Frame {
  const { cols, rows } = meta;
  // how far along its blade each steel cell is, in each pose: the nearest point of the curve
  const along = BLADE.map(([[ax, ay], [bx, by], [cx, cy]], p) => {
    const pts: [number, number][] = [];
    for (let i = 0; i <= 60; i++) {
      const u = i / 60;
      pts.push([(1 - u) ** 2 * ax + 2 * (1 - u) * u * bx + u * u * cx, (1 - u) ** 2 * ay + 2 * (1 - u) * u * by + u * u * cy]);
    }
    const out = new Float32Array(cols * rows);
    for (let y = 0; y < rows; y++)
      for (let x = 0; x < cols; x++) {
        if (MAT[p][y][x] !== "2") continue;
        let best = 0, bd = Infinity;
        pts.forEach(([px, py], i) => {
          const d = (px - x - 0.5) ** 2 + (2 * (py - y - 0.5)) ** 2;
          if (d < bd) (bd = d), (best = i / 60);
        });
        out[y * cols + x] = best;
      }
    return out;
  });

  return (t, { color } = {}) => {
    const u = ((t % LOOP) + LOOP) % LOOP;
    // the arm flexes up, holds while the glint runs, and eases back down
    const flex = smooth((u - 0.6) / 0.6) * (1 - smooth((u - 3.2) / 0.6));
    const p = Math.round(flex * 2);
    const at = -2 * HALF + ((u - START) / RUN) * (1 + 4 * HALF);
    const art = ART[p], mat = MAT[p];
    const out: string[] = [];
    for (let y = 0; y < rows; y++) {
      let line = "";
      for (let x = 0; x < cols; x++) {
        let ch = art[y][x];
        if (color) {
          const m = mat[y][x];
          // the cloth's ripple: bands of light and shadow drifting out across the flag
          const w = Math.sin(x * 0.21 - y * 0.16 - (u / LOOP) * RIPPLE * 2 * Math.PI);
          const shade = w > 0.5 ? 2 : w < -0.5 ? 0 : 1;
          let c = 0;
          if (m === "1") c = shade;
          else if (m === "3") c = 7 + shade;
          else if (m === "2") {
            const k = smooth(1 - Math.abs(along[p][y * cols + x] - at) / HALF);
            c = k > 0.6 ? 6 : k > 0.2 ? 5 : 3 + Math.min(1, shade);
            if (k > 0.6 && ch === "#") ch = "=";
          }
          color[y * cols + x] = c;
        } else if (mat[y][x] === "2" && ch === "#" && Math.abs(along[p][y * cols + x] - at) < HALF * 0.4) ch = "=";
        line += ch;
      }
      out.push(line);
    }
    return out.join("\n");
  };
}
