const LOOP = 4.8; // seconds: four beats, one glint and two ripples
const BEAT_EVERY = 1.2;
const SWELL = [[0, 0.12], [0.24, 0.36]]; // when in a beat the heart is swollen: lub, dub
const HEART_FROM = 56; // the heart's columns start here, so a beat changes only them
const GLINT = [3.6, 4.4]; // when in the loop the glint runs down the dagger
const SOLID = "8bdqpPY";

export default function stedeBonnet(): Frame {
  const { cols, rows } = meta;
  const stuff = (s: string[]) => s.map((r) => [...r].map((c) => parseInt(c, 36)));
  const rest = { art: REST, stuff: stuff(STUFF_REST) }, beat = { art: BEAT, stuff: stuff(STUFF_BEAT) };

  return (t, { color } = {}) => {
    const u = ((t % LOOP) + LOOP) % LOOP;
    const swollen = SWELL.some(([a, b]) => u % BEAT_EVERY >= a && u % BEAT_EVERY < b);
    const g = u >= GLINT[0] && u < GLINT[1] ? (u - GLINT[0]) / (GLINT[1] - GLINT[0]) : -1;
    const out: string[] = [];
    for (let y = 0; y < rows; y++) {
      let line = "";
      for (let x = 0; x < cols; x++) {
        const pose = swollen && x >= HEART_FROM ? beat : rest;
        let ch = pose.art[y][x];
        const kind = pose.stuff[y][x];
        // the cloth's folds: a wave across it, two a loop, darkening what lies in a trough
        const fold = Math.sin(0.21 * x + 0.13 * y - (2 * Math.PI * 2 * u) / LOOP);
        const shade = fold < -0.62 ? 2 : fold < -0.12 ? 1 : 0;
        // the glint, a slanted band running down the dagger
        const lit = g >= 0 && (kind === 3 || kind === 4) && Math.abs(y - 0.6 * (x - 10) - (g * (rows + 14) - 7)) < 2.2;
        if (lit && SOLID.includes(ch)) ch = "/";
        line += ch;
        if (color && ch !== " ")
          color[y * cols + x] =
            kind === 2 ? (swollen ? 4 : shade === 2 ? 5 : 3)
            : kind === 3 ? (lit ? 7 : shade === 2 ? 8 : 6)
            : kind === 4 ? (lit ? 7 : 1 + (shade >> 1))
            : kind === 5 ? 5
            : shade;
      }
      out.push(line);
    }
    return out.join("\n");
  };
}
